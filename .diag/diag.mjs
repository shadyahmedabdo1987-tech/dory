// Read-only check of a member's sign-in code in production (anonymous user, no writes).
import { createHash } from 'node:crypto';
const KEY = process.env.KEY, PROJECT = 'dory-app-eff88';
const [INVITE, RAWPHONE, LOGIN] = [process.env.INVITE, process.env.PHONE, process.env.LOGIN];
const sha = (s) => createHash('sha256').update(s).digest('hex');
let d = RAWPHONE.replace(/[^\d+]/g, '');
if (d.startsWith('+')) d = d.slice(1); else if (d.startsWith('00')) d = d.slice(2); else if (d.startsWith('0')) d = '20' + d.slice(1);
const auth = await (await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signUp?key=${KEY}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"returnSecureToken":true}' })).json();
const H = { Authorization: `Bearer ${auth.idToken}` };
const BASE = `https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/(default)/documents`;
const get = async (p) => { const r = await fetch(`${BASE}/${p}`, { headers: H }); return { status: r.status, body: r.ok ? await r.json() : await r.text() }; };
const str = (doc, k) => doc?.fields?.[k]?.stringValue;
const code = INVITE.trim().toUpperCase().replace(/[^A-Z0-9]/g, '');
const inv = await get(`invites/${code}`);
console.log('invite', inv.status);
const cid = str(inv.body, 'circleId');
console.log('cid', cid);
const ph = await get(`circles/${cid}/phones/${d}`);
console.log('phone doc', ph.status, 'memberId', str(ph.body, 'memberId'));
const mid = str(ph.body, 'memberId');
const marker = await get(`circles/${cid}/phones/code-${mid}`);
console.log('code marker', marker.status, str(marker.body, 'memberId'));
const digits = LOGIN.replace(/\D/g, '');
const lc = `${digits.slice(0, 3)}-${digits.slice(3)}`;
const k = `k-${sha(`dory:code:v1:${cid}:${mid}:${lc}`).slice(0, 40)}`;
const kd = await get(`circles/${cid}/phones/${k}`);
console.log('code fingerprint doc', kd.status, str(kd.body, 'memberId'));
const sec = await get(`circles/${cid}/secrets/${mid}`);
console.log('secret (expect 403 for non-member)', sec.status);
const dir = await get(`directory/${cid}`);
console.log('directory', dir.status, 'members', dir.body?.fields?.memberCount?.integerValue);
